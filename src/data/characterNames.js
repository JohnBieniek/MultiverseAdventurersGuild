const conventionalNameSpecies = ['Dwarf', 'Elf', 'Fairy', 'Gnome', 'Giant', 'Halfling', 'Human']
const nameComponents = (species, name) => { const parts = name.split(/\s+/); return { first: parts[0], last: species === 'Giant' ? parts.slice(1).join(' ') : parts.at(-1) } }
Object.entries(characterNamesBySpecies).forEach(([species, names]) => { const expected = expectedNameCounts[species] || 500; if (names.some(name => name.trim().split(/\s+/).length > 6)) throw new Error(`${species} names may not exceed six words`); if (names.length !== expected || new Set(names).size !== expected) throw new Error(`${species} must have exactly ${expected} unique names`); if (!conventionalNameSpecies.includes(species)) return; const first = names.map(name => nameComponents(species, name).first); const last = names.map(name => nameComponents(species, name).last); const lastSet = new Set(last); if (new Set(first).size !== expected || new Set(last).size !== expected || first.some(name => lastSet.has(name))) throw new Error(`${species} name components must be unique and non-overlapping`) })

export const randomCharacterName = (species, archetype = '') => { if (species === 'Cyborg') { const matching = cyborgNames.filter(entry => !archetype || entry.archetype === archetype); const choices = matching.length ? matching : cyborgNames; return choices[Math.floor(Math.random() * choices.length)]?.name || '' } const names = characterNamesBySpecies[species]; return names?.[Math.floor(Math.random() * names.length)] || '' }

