const nameComponents = (species, name) => { const parts = name.split(/\s+/); return { first: parts[0], last: species === 'Giant' ? parts.slice(1).join(' ') : parts.at(-1) } }
const fairyFirsts = characterNamesBySpecies.Fairy.map(name => name.split(/\s+/)[0]); const fairyBynames = characterNamesBySpecies.Fairy.map(name => name.split(/\s+/)[1]).filter(Boolean); if (new Set(fairyFirsts).size !== 500 || fairyBynames.length !== 250 || new Set(fairyBynames).size !== 250 || fairyFirsts.some(name => new Set(fairyBynames).has(name))) throw new Error('Fairy first names and optional bynames must be unique and non-overlapping'); Object.entries(characterNamesBySpecies).forEach(([species, names]) => { const expected = expectedNameCounts[species] || 500; if (names.some(name => name.trim().split(/\s+/).length > 6)) throw new Error(`${species} names may not exceed six words`); if (names.length !== expected || new Set(names).size !== expected) throw new Error(`${species} must have exactly ${expected} unique names`); if (!conventionalNameSpecies.includes(species)) return; const first = names.map(name => nameComponents(species, name).first); const last = names.map(name => nameComponents(species, name).last); const lastSet = new Set(last); if (new Set(first).size !== expected || new Set(last).size !== expected || first.some(name => lastSet.has(name))) throw new Error(`${species} name components must be unique and non-overlapping`) })

